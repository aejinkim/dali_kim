// Reads every CSS custom property declared in src/app/globals.css and writes
// their names as TypeScript unions, so `cssVar('--color-txt-primary')` (typo)
// fails type-check instead of silently rendering nothing.
//   node scripts/gen-token-types.mjs          write the file
//   node scripts/gen-token-types.mjs --check  exit 1 if the file is stale (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const CSS = 'src/app/globals.css';
const OUT = 'src/lib/design-tokens.generated.ts';

const css = readFileSync(CSS, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const names = [...new Set([...css.matchAll(/(?:^|[;{\s])(--[a-z0-9-]+)\s*:/gi)].map((m) => m[1]))].sort();

const union = (list) => (list.length ? list.map((n) => `  | '${n}'`).join('\n') : '  never');
const colors = names.filter((n) => n.startsWith('--color-'));
const semantic = colors.filter((n) => /^--color-(text|surface|border|accent)-/.test(n));

const body = `// Generated by scripts/gen-token-types.mjs from ${CSS}. Do not edit.

export type CssToken =
${union(names)};

export type ColorToken =
${union(colors)};

export type SemanticColorToken =
${union(semantic)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error(`${OUT} is out of date with ${CSS}. Run: npm run tokens`);
    process.exit(1);
  }
  console.log(`tokens: ${names.length} names, up to date`);
} else {
  writeFileSync(OUT, body);
  console.log(`tokens: wrote ${names.length} names (${colors.length} colors, ${semantic.length} semantic) to ${OUT}`);
}
